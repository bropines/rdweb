// Writes src/react/fonts/nerdSymbols.ts from a WOFF2 of "Symbols Nerd Font Mono"
// (https://github.com/ryanoasis/nerd-fonts, NerdFontsSymbolsOnly, converted
// from TTF with fontTools). Usage: node scripts/gen-nerd-font.mjs <file.woff2> <version>
import { readFileSync, writeFileSync } from "node:fs";

const [file, version] = process.argv.slice(2);
if (!file || !version) throw new Error("usage: gen-nerd-font.mjs <file.woff2> <version>");
const b64 = readFileSync(file).toString("base64");
writeFileSync(
  "src/react/fonts/nerdSymbols.ts",
  `// Symbols Nerd Font Mono ${version} (WOFF2), see NOTICE for licenses. Generated by\n` +
    `// scripts/gen-nerd-font.mjs; loaded on demand by the terminal (icons in shell prompts).\n` +
    `export const NERD_SYMBOLS_WOFF2 = "${b64}";\n`,
);
